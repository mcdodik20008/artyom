# -*- coding: utf-8 -*-
"""
ЗАДАЧА 13 - IP-адреса и маски

УСЛОВИЕ:
При регистрации в компьютерной системе каждому пользователю выдаётся
IP-адрес из диапазона 192.168.32.160 - 192.168.32.191.
При этом используется маска подсети.

Определите маску подсети для данного диапазона, если известно, что маска
представляет собой последовательность единиц, за которыми следуют нули.

Ответ запишите в виде четырёх десятичных чисел, разделённых точками.
"""

# Решение без библиотеки (для понимания)
print("Способ 1: Ручной расчёт")
print("=" * 60)

# Переводим IP-адреса в двоичный вид
start_ip = "192.168.32.160"
end_ip = "192.168.32.191"

# Последний октет: от 160 до 191
start_last = 160
end_last = 191

print(f"Диапазон: {start_ip} - {end_ip}")
print(f"\nПоследний октет:")
print(f"  {start_last} = {bin(start_last)[2:].zfill(8)}")
print(f"  {end_last}   = {bin(end_last)[2:].zfill(8)}")

# Количество адресов в диапазоне
count = end_last - start_last + 1
print(f"\nКоличество адресов: {count}")

# Для 32 адресов нужно 5 бит (2^5 = 32)
# Значит, маска заканчивается на 32 - 5 = 27 единиц
# Или в последнем октете: 11100000 = 224

mask = "255.255.255.224"
print(f"\nМаска подсети: {mask}")

# Проверка
print("\nПроверка:")
print(f"255 = {bin(255)[2:].zfill(8)}")
print(f"224 = {bin(224)[2:].zfill(8)}")
print(f"Маска в двоичном виде: 11111111.11111111.11111111.11100000")

# Решение с использованием модуля ipaddress
print("\n" + "=" * 60)
print("Способ 2: С использованием модуля ipaddress")
print("=" * 60)

import ipaddress

# Создаём сеть, которая включает оба адреса
network = ipaddress.IPv4Network(f"{start_ip}/27", strict=False)

print(f"Сеть: {network}")
print(f"Маска: {network.netmask}")
print(f"Первый адрес: {network.network_address}")
print(f"Последний адрес: {network.broadcast_address}")
print(f"Количество адресов: {network.num_addresses}")

print(f"\nОТВЕТ: {network.netmask}")
