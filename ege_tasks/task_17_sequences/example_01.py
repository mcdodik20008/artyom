"""
ЗАДАЧА 17 - Последовательности чисел

Условие:
В файле содержится последовательность натуральных чисел.
Найдите количество пар элементов последовательности, в которых:
1. Хотя бы одно число кратно 43
2. Сумма элементов пары меньше максимального элемента, кратного 43

Формат ответа: количество пар и максимальная сумма среди найденных пар
"""

# Пример данных (в реальной задаче читаем из файла)
numbers = [43, 86, 100, 129, 150, 200, 215, 430, 500, 645]

# Находим максимальный элемент, кратный 43
max_43 = max([x for x in numbers if x % 43 == 0])
print(f"Максимальный элемент, кратный 43: {max_43}")

# Ищем пары
count = 0
max_sum = 0

for i in range(len(numbers) - 1):
    for j in range(i + 1, len(numbers)):
        # Проверяем условия
        if (numbers[i] % 43 == 0 or numbers[j] % 43 == 0):
            pair_sum = numbers[i] + numbers[j]
            if pair_sum < max_43:
                count += 1
                max_sum = max(max_sum, pair_sum)
                print(f"Пара: ({numbers[i]}, {numbers[j]}), сумма = {pair_sum}")

print(f"\nОтвет:")
print(f"Количество пар: {count}")
print(f"Максимальная сумма: {max_sum}")
