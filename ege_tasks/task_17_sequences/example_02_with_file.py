"""
ЗАДАЧА 17 - Работа с файлом

Условие:
В файле содержится последовательность целых чисел.
Найдите количество пар соседних элементов, в которых:
1. Оба числа положительные
2. Произведение заканчивается на 6
"""

# Создадим тестовый файл
test_data = [12, 3, 8, 15, 4, 9, 2, 13, 6, 7]

with open('numbers.txt', 'w') as f:
    for num in test_data:
        f.write(str(num) + '\n')

# Читаем файл
with open('numbers.txt', 'r') as f:
    numbers = [int(line.strip()) for line in f]

print("Числа:", numbers)

# Ищем пары соседних элементов
count = 0
max_product = 0

for i in range(len(numbers) - 1):
    a, b = numbers[i], numbers[i + 1]

    # Проверяем условия
    if a > 0 and b > 0:
        product = a * b
        if product % 10 == 6:  # Заканчивается на 6
            count += 1
            max_product = max(max_product, product)
            print(f"Пара: ({a}, {b}), произведение = {product}")

print(f"\nОтвет:")
print(f"Количество пар: {count}")
print(f"Максимальное произведение: {max_product}")

# Правило: произведение заканчивается на 6, если:
# - одно число заканчивается на 2, другое на 3, 8
# - одно число заканчивается на 4, другое на 4, 9
# - одно число заканчивается на 6, другое на 1, 6
# - одно число заканчивается на 8, другое на 2, 7
