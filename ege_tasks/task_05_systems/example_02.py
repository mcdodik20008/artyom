"""
ЗАДАЧА 5 - Системы счисления (сложнее)

Условие:
Найдите количество натуральных чисел x, для которых выполняется:
111₁₆ ≤ x ≤ 333₈

И при этом x делится на 3
"""

# Переводим границы
left = int('111', 16)   # 16-ричное: 1*16² + 1*16 + 1 = 256 + 16 + 1 = 273
right = int('333', 8)   # 8-ричное: 3*8² + 3*8 + 3 = 192 + 24 + 3 = 219

print(f"111₁₆ = {left}")
print(f"333₈ = {right}")

# Проверяем условие
if left > right:
    print(f"Левая граница больше правой! Диапазон пустой.")
    count = 0
else:
    # Считаем числа, делящиеся на 3
    count = 0
    for x in range(left, right + 1):
        if x % 3 == 0:
            count += 1

    print(f"Количество чисел, делящихся на 3: {count}")

# Альтернативный быстрый способ для делимости
if left <= right:
    # Найдем первое число >= left, делящееся на 3
    first = left + (3 - left % 3) % 3
    # Найдем последнее число <= right, делящееся на 3
    last = right - right % 3

    if first <= last:
        count_fast = (last - first) // 3 + 1
        print(f"Быстрый подсчет: {count_fast}")
