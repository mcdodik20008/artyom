"""
ЗАДАЧА 5 - Системы счисления

Условие:
Сколько существует натуральных чисел x, для которых выполняется неравенство:
10110₂ ≤ x ≤ 101₈

Решение:
1. Переводим числа из двоичной и восьмеричной систем в десятичную
2. Находим количество чисел в диапазоне
"""

# Способ 1: Прямое преобразование
left = int('10110', 2)   # Двоичное число в десятичное
right = int('101', 8)     # Восьмеричное число в десятичное

print(f"10110₂ = {left}")  # 22
print(f"101₈ = {right}")   # 65

# Количество натуральных чисел в диапазоне [left, right]
count = right - left + 1
print(f"Количество чисел: {count}")

# Способ 2: С проверкой каждого числа
count_check = 0
for x in range(left, right + 1):
    count_check += 1

print(f"Проверка: {count_check}")

