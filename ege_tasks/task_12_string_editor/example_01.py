# -*- coding: utf-8 -*-
"""
ЗАДАЧА 12 - Редактор строк

УСЛОВИЕ:
Исполнитель Редактор получает на вход строку цифр и преобразовывает её.
Редактор может выполнять две команды:
1. заменить (x, y) - заменить все вхождения подстроки x на подстроку y
2. обработать строку в заданной последовательности

Дана программа для Редактора:
НАЧАЛО
ПОКА нашлось (52) ИЛИ нашлось (322) ИЛИ нашлось (222)
    ЕСЛИ нашлось (52)
        ТО заменить (52, 2)
        ИНАЧЕ заменить (322, 5)
    КОНЕЦ ЕСЛИ
    ЕСЛИ нашлось (222)
        ТО заменить (222, 3)
    КОНЕЦ ЕСЛИ
КОНЕЦ ПОКА
КОНЕЦ

Какая строка получится, если на вход подать строку "5"*70 (70 пятёрок)?
"""

# Решение
s = "5" * 70

# Счётчик итераций для отладки
iteration = 0

while "52" in s or "322" in s or "222" in s:
    iteration += 1

    # Первое условие
    if "52" in s:
        s = s.replace("52", "2")
    else:
        s = s.replace("322", "5")

    # Второе условие
    if "222" in s:
        s = s.replace("222", "3")

    # Показываем первые несколько итераций
    if iteration <= 5:
        print(f"Итерация {iteration}: {s[:50]}{'...' if len(s) > 50 else ''}")

print(f"\nВсего итераций: {iteration}")
print(f"Итоговая строка: {s}")
print(f"Длина строки: {len(s)}")

# Подсчёт количества каждой цифры
from collections import Counter
counts = Counter(s)
print(f"\nСостав строки:")
for digit in sorted(counts.keys()):
    print(f"  Цифра '{digit}': {counts[digit]} раз")

print("\n" + "=" * 60)
print("СОВЕТ: В таких задачах важно правильно применять replace()")
print("и учитывать порядок замен!")
print("=" * 60)
