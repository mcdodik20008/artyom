# -*- coding: utf-8 -*-
"""
ЗАДАЧА 12 - Редактор строк (сложнее)

УСЛОВИЕ:
Редактор обрабатывает строку по алгоритму:
НАЧАЛО
ПОКА нашлось (01) ИЛИ нашлось (02) ИЛИ нашлось (03)
    заменить (01, 2302)
    заменить (02, 10)
    заменить (03, 201)
КОНЕЦ ПОКА
КОНЕЦ

Дана строка "03" + "1" * 20 (то есть "03111...111", где 20 единиц).
Сколько цифр "2" будет в итоговой строке?
"""

# Решение
s = "03" + "1" * 20

print(f"Начальная строка: {s}")
print(f"Длина: {len(s)}\n")

iteration = 0
max_iterations = 1000  # Защита от зацикливания

while ("01" in s or "02" in s or "03" in s) and iteration < max_iterations:
    iteration += 1

    # Важно: порядок замен имеет значение!
    s = s.replace("01", "2302")
    s = s.replace("02", "10")
    s = s.replace("03", "201")

    # Показываем первые итерации
    if iteration <= 3:
        preview = s if len(s) <= 60 else s[:60] + "..."
        print(f"Итерация {iteration}: {preview}")

print(f"\nВсего итераций: {iteration}")
print(f"Длина итоговой строки: {len(s)}")

# Подсчитываем количество каждой цифры
count_0 = s.count("0")
count_1 = s.count("1")
count_2 = s.count("2")
count_3 = s.count("3")

print(f"\nРезультат:")
print(f"  Цифра '0': {count_0}")
print(f"  Цифра '1': {count_1}")
print(f"  Цифра '2': {count_2}")
print(f"  Цифра '3': {count_3}")

print(f"\nОТВЕТ: Количество цифр '2' = {count_2}")
