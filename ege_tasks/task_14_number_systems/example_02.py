"""
ЗАДАЧА 14 - Системы счисления (поиск x)

УСЛОВИЕ:
Найдите наименьшее основание системы счисления x, при котором верно равенство:
123(x) + 321(x) = 444(x)

где запись вида abc(x) означает число в системе счисления с основанием x.
"""

def from_base(s, base):
    """Переводит строку из системы с основанием base в десятичную"""
    result = 0
    for digit in s:
        result = result * base + int(digit)
    return result

# Перебираем основания системы счисления
print("Проверяем разные основания:\n")

for x in range(2, 20):
    # Проверяем, что все цифры корректны для данного основания
    # В системе с основанием x используются цифры от 0 до x-1
    if x <= 4:  # Цифра 4 не может существовать в системах с основанием <= 4
        continue

    # Переводим числа в десятичную систему
    num1 = from_base("123", x)
    num2 = from_base("321", x)
    num3 = from_base("444", x)

    # Проверяем равенство
    if num1 + num2 == num3:
        print(f"x = {x}:")
        print(f"  123({x}) = {num1}")
        print(f"  321({x}) = {num2}")
        print(f"  444({x}) = {num3}")
        print(f"  {num1} + {num2} = {num3} ✓")
        print(f"\nОТВЕТ: {x}")
        break
    else:
        if x <= 8:  # Показываем первые несколько попыток
            print(f"x = {x}: {num1} + {num2} = {num1+num2} != {num3}")

