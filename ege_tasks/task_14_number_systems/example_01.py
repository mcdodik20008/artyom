# -*- coding: utf-8 -*-
"""
ЗАДАЧА 14 - Системы счисления и уравнения

УСЛОВИЕ:
Значение выражения 49^7 + 7^21 - 7 записали в системе счисления с основанием 7.
Сколько цифр 6 содержится в этой записи?
"""

# Решение
expression = 49**7 + 7**21 - 7

print(f"Вычисляем: 49^7 + 7^21 - 7")
print(f"Значение в 10-й системе: {expression}")
print(f"Это число из {len(str(expression))} цифр!\n")

# Переводим в 7-ричную систему
def to_base(num, base):
    """Переводит число в систему счисления с заданным основанием"""
    if num == 0:
        return "0"

    digits = []
    while num > 0:
        digits.append(str(num % base))
        num //= base

    return ''.join(reversed(digits))

result_base7 = to_base(expression, 7)

print(f"В 7-ричной системе: {result_base7[:50]}...")
print(f"Длина: {len(result_base7)} цифр")

# Подсчитываем количество шестёрок
count_6 = result_base7.count('6')

print(f"\nКоличество цифр '6': {count_6}")

# Проверим математически
print("\n" + "=" * 60)
print("МАТЕМАТИЧЕСКИЙ АНАЛИЗ:")
print("=" * 60)

print("49^7 = (7^2)^7 = 7^14")
print("7^21 = 7^21")
print("Выражение: 7^14 + 7^21 - 7 = 7^14 + 7^21 - 7^1")
print("\n7^14 в 7-ричной системе: 1" + "0"*14)
print("7^21 в 7-ричной системе: 1" + "0"*21)
print("7^1 в 7-ричной системе: 10")

# Выполняем сложение
#   1000000000000000000000 (7^21)
# +       10000000000000 (7^14)
# -                   10 (7)

print("\nОТВЕТ:", count_6)
