"""
ЗАДАЧА 16 - Рекурсия

Условие:
Алгоритм вычисляет функцию F(n):

def F(n):
    if n > 2:
        return F(n - 1) + F(n - 2)
    else:
        return n

Чему равно F(8)?
"""

# Простое решение - прямой вызов
def F(n):
    if n > 2:
        return F(n - 1) + F(n - 2)
    else:
        return n

result = F(8)
print(f"F(8) = {result}")

# Объяснение как работает:
# F(1) = 1
# F(2) = 2
# F(3) = F(2) + F(1) = 2 + 1 = 3
# F(4) = F(3) + F(2) = 3 + 2 = 5
# F(5) = F(4) + F(3) = 5 + 3 = 8
# F(6) = F(5) + F(4) = 8 + 5 = 13
# F(7) = F(6) + F(5) = 13 + 8 = 21
# F(8) = F(7) + F(6) = 21 + 13 = 34

# Пошаговый подсчёт
print("\nПошаговое вычисление:")
for i in range(1, 9):
    print(f"F({i}) = {F(i)}")
