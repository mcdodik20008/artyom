def count_divisors(n):
    count = 0
    for i in range(1, int(n**0.5) + 1):
        if n % i == 0:
            count += 1
            if i != n // i:
                count += 1
    return count

print("  Числа с 3 делителями:")
for num in range(50, 101):
    if count_divisors(num) == 3:
        print(f"  {num} = {int(num**0.5)}²")

