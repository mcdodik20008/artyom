# -*- coding: utf-8 -*-
"""
ЗАДАЧА 15 - Логические выражения и побитовые операции

УСЛОВИЕ:
Обозначим через ДЕЛ(n, m) утверждение "натуральное число n делится на натуральное число m".
Для какого наибольшего натурального числа A формула

ДЕЛ(x, A) -> (ДЕЛ(x, 6) -> ДЕЛ(x, 4))

истинна при любом натуральном x?
"""

def implies(a, b):
    """Импликация: A -> B эквивалентно (не A) или B"""
    return (not a) or b

# Проверяем для разных значений A
print("Проверяем формулу для разных A:\n")

for A in range(1, 50):
    # Проверяем на большом диапазоне x
    valid = True

    for x in range(1, 1000):
        # ДЕЛ(x, A) -> (ДЕЛ(x, 6) -> ДЕЛ(x, 4))
        result = implies(x % A == 0, implies(x % 6 == 0, x % 4 == 0))

        if not result:
            valid = False
            break

    if valid:
        print(f"A = {A}: формула ИСТИННА для всех x")
    else:
        # Показываем только первые несколько неподходящих
        if A <= 15:
            print(f"A = {A}: формула ЛОЖНА (контрпример: x = {x})")

print("\n" + "=" * 60)
print("АНАЛИЗ:")
print("=" * 60)

print("\nФормула: ДЕЛ(x, A) -> (ДЕЛ(x, 6) -> ДЕЛ(x, 4))")
print("\nКогда формула может быть ложной?")
print("Только когда ДЕЛ(x, A) = истина, а (ДЕЛ(x, 6) -> ДЕЛ(x, 4)) = ложь")
print("\n(ДЕЛ(x, 6) -> ДЕЛ(x, 4)) ложна, когда:")
print("  ДЕЛ(x, 6) = истина И ДЕЛ(x, 4) = ложь")
print("\nТо есть x делится на 6, но не делится на 4")
print("Примеры таких x: 6, 18, 30, 42, 54, 66, 78, 90...")

print("\nЧтобы формула была истинна для всех x,")
print("A не должно делить ни одно из этих чисел.")
print("\nНаибольшее такое A = 12")

# Проверка
print("\n" + "=" * 60)
print("ПРОВЕРКА для A = 12 и A = 13:")
print("=" * 60)

for A in [12, 13]:
    print(f"\nA = {A}:")
    problematic_x = [6, 18, 30, 42, 54, 66, 78, 90]
    for x in problematic_x[:6]:
        divides_A = (x % A == 0)
        divides_6 = (x % 6 == 0)
        divides_4 = (x % 4 == 0)
        result = implies(divides_A, implies(divides_6, divides_4))
        print(f"  x={x}: ДЕЛ({x},{A})={divides_A}, формула={result}")
