"""
ЗАДАЧА 25 - Делители чисел (продвинутый уровень)

Условие:
Найдите все натуральные числа в диапазоне [200000, 250000],
которые имеют ровно 6 нечётных делителей.
Для каждого найденного числа выведите его и максимальный нечётный делитель.
"""

def get_odd_divisors(n):
    """Возвращает список всех нечётных делителей числа n"""
    divisors = []
    i = 1
    while i * i <= n:
        if n % i == 0:
            if i % 2 == 1:  # i - нечётный
                divisors.append(i)
            if i != n // i and (n // i) % 2 == 1:  # n//i - нечётный
                divisors.append(n // i)
        i += 1
    return sorted(divisors)

# Решение
print("Числа с ровно 6 нечётными делителями:\n")
count = 0

for num in range(200000, 250001):
    odd_divs = get_odd_divisors(num)

    if len(odd_divs) == 6:
        count += 1
        max_odd = max(odd_divs)
        print(f"{num}  {max_odd}")

        # Покажем первые несколько для примера
        if count == 1:
            print(f"  Все нечётные делители: {odd_divs}")

print(f"\nВсего найдено: {count}")

