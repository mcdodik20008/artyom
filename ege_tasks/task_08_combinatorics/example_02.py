"""
ЗАДАЧА 8 - Комбинаторика (с повторениями)

Условие:
Сколько существует четырёхзначных чисел, которые можно записать
с помощью цифр 2, 4, 6, 8 (цифры могут повторяться),
и которые начинаются и заканчиваются на чётную цифру?

Решение:
"""

# Все цифры 2, 4, 6, 8 - чётные, поэтому условие выполняется всегда!

digits = [2, 4, 6, 8]
count = 0

for a in digits:  # Первая цифра (чётная)
    for b in digits:  # Вторая цифра (любая)
        for c in digits:  # Третья цифра (любая)
            for d in digits:  # Четвёртая цифра (чётная)
                count += 1

print(f"Способ 1 (перебор): {count}")

# Математическое решение
# 4 варианта для первой позиции
# 4 варианта для второй позиции
# 4 варианта для третьей позиции
# 4 варианта для четвёртой позиции
count_math = 4 * 4 * 4 * 4
print(f"Способ 2 (формула): {count_math}")

# Более сложный вариант: если бы были цифры 1,2,3,4,5,6
print("\n--- Дополнительный пример ---")
digits2 = [1, 2, 3, 4, 5, 6]
even_digits = [2, 4, 6]
count2 = 0

for a in even_digits:  # Первая - чётная
    for b in digits2:   # Вторая - любая
        for c in digits2:   # Третья - любая
            for d in even_digits:  # Четвёртая - чётная
                count2 += 1

print(f"Числа из цифр 1-6, начинающиеся и оканчивающиеся на чётную: {count2}")
print(f"Формула: 3 × 6 × 6 × 3 = {3*6*6*3}")
